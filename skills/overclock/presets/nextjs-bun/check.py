#!/usr/bin/env python3
"""Validates the project without running the app: typecheck, lint and unit tests.

With --only, fails only for problems in the given files. Type errors in other files are
printed as OTHER and do not fail: they belong to tasks still in progress in the shared tree.
Without --only, checks the whole project. With --full, also runs the production build.

Overclock Runtime preset for TypeScript web apps (Next.js, Bun, ESLint, Vitest). Adapt the tools
to the project: another test runner, another build command, another package manager.

Run (from the project root):
    python3 .claude/scripts/check.py --only src/lib/cart.ts,src/lib/cart.test.ts
    python3 .claude/scripts/check.py            # whole project: typecheck, lint, unit tests
    python3 .claude/scripts/check.py --full     # the above plus `next build`

Exit code: 0 if nothing failed in scope, 1 otherwise. A step whose tool is not installed yet
(no node_modules/.bin/<tool>) is reported as SKIP and does not fail.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BIN = ROOT / "node_modules" / ".bin"
CODE = {".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs"}
TSC_ERROR = re.compile(r"^(.+?)\((\d+),(\d+)\): error (TS\d+): (.*)$")


def run(tool, *args):
    """Runs a tool from node_modules/.bin. Returns (exit code, output) or None if missing."""
    exe = BIN / tool
    if not exe.exists():
        return None
    proc = subprocess.run([str(exe), *args], cwd=ROOT, capture_output=True, text=True)
    return proc.returncode, (proc.stdout + proc.stderr).strip()


def tail(output, lines=60):
    rows = output.splitlines()
    return "\n".join(rows[-lines:])


def typecheck(only):
    if not (ROOT / "tsconfig.json").exists():
        print("SKIP typecheck: no tsconfig.json")
        return True
    result = run("tsc", "--noEmit", "--pretty", "false", "--incremental", "false")
    if result is None:
        print("SKIP typecheck: typescript is not installed")
        return True
    code, output = result
    own, other, unparsed = [], [], []
    for line in output.splitlines():
        m = TSC_ERROR.match(line)
        if not m:
            if line.strip() and "error" in line:
                unparsed.append(line)
            continue
        path = Path(m.group(1)).as_posix()
        # Types generated by a running `next dev` or `next build` can be stale; they are not task code.
        generated = path.startswith(".next/")
        (own if not generated and (only is None or path in only) else other).append(line)
    for line in other:
        print(f"OTHER {line}")
    for line in own + unparsed:
        print(f"ERROR {line}")
    # A nonzero exit with no parsed error means tsc failed for another reason (bad config, crash).
    failed = bool(own) or bool(unparsed) or (only is None and code != 0 and not other)
    print(f"typecheck: {len(own)} errors in scope, {len(other)} in other files")
    return not failed


def lint(only):
    targets = ["."] if only is None else sorted(p for p in only if Path(p).suffix in CODE and (ROOT / p).exists())
    if not targets:
        print("SKIP lint: no code files in scope")
        return True
    result = run("eslint", *targets)
    if result is None:
        print("SKIP lint: eslint is not installed")
        return True
    code, output = result
    if code != 0:
        print(tail(output))
    print(f"lint: {'ok' if code == 0 else 'failed'}")
    return code == 0


def unit_tests(only):
    if only is None:
        result = run("vitest", "run", "--passWithNoTests")
    else:
        targets = sorted(p for p in only if Path(p).suffix in CODE and (ROOT / p).exists())
        if not targets:
            print("SKIP tests: no code files in scope")
            return True
        result = run("vitest", "related", "--run", "--passWithNoTests", *targets)
    if result is None:
        print("SKIP tests: vitest is not installed")
        return True
    code, output = result
    if code != 0:
        print(tail(output))
    print(f"tests: {'ok' if code == 0 else 'failed'}")
    return code == 0


def build():
    result = run("next", "build")
    if result is None:
        print("SKIP build: next is not installed")
        return True
    code, output = result
    if code != 0:
        print(tail(output))
    print(f"build: {'ok' if code == 0 else 'failed'}")
    return code == 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--only", help="comma-separated files, relative to the project root")
    ap.add_argument("--full", action="store_true", help="also run the production build")
    args = ap.parse_args()
    if args.only and args.full:
        sys.exit("--only and --full do not go together: the build is always the whole project")

    only = None
    if args.only:
        only = {Path(p.strip()).as_posix() for p in args.only.split(",") if p.strip()}
        missing = sorted(p for p in only if not (ROOT / p).exists())
        for path in missing:
            print(f"note: {path} does not exist")

    steps = [typecheck(only), lint(only), unit_tests(only)]
    if args.full:
        steps.append(build())
    ok = all(steps)
    print("CHECK OK" if ok else "CHECK FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
